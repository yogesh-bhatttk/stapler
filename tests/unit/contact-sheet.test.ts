import { describe, it, expect } from 'vitest';
import { PDFDocument, PDFName, PDFDict } from 'pdf-lib';
import { processWorkerImpl } from '../../src/core/workers/process.worker';

describe('DOC-09: Contact sheet export', () => {
  it('tiles 20 page thumbnails into a 4-column contact sheet', async () => {
    // Create a 1x1 dummy JPEG image byte array
    // Minimal valid 1x1 JPEG image bytes
    const sampleJpeg = await createDummyJpeg();

    const jpegs = Array.from({ length: 20 }, () => sampleJpeg);

    const outBytes = await processWorkerImpl.contactSheetExport(jpegs, 4);

    expect(outBytes).toBeDefined();
    expect(outBytes.length).toBeGreaterThan(0);

    const pdf = await PDFDocument.load(outBytes);
    expect(pdf.getPageCount()).toBe(1);

    const page = pdf.getPage(0);
    const resources = page.node.Resources();
    expect(resources).toBeDefined();

    const xObjects = resources?.lookupMaybe(PDFName.of('XObject'), PDFDict);
    expect(xObjects).toBeDefined();
    // Should have embedded 20 images
    expect(xObjects?.entries().length).toBe(20);
  });
});

